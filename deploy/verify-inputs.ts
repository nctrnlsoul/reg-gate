// Writes the block explorer verification inputs for the current deployment:
//   contracts/verify/<Contract>.standard-input.json   (solc standard JSON from contracts/src)
//   contracts/verify/README.md                         (addresses and ABI-encoded constructor arguments)
// Read-only on chain: it reads nothing from the network and needs no key.
//
//   bun deploy/verify-inputs.ts

import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { encodeAbiParameters, parseEther, type Address } from 'viem'
import { type Deployment, deploymentFile, loadArtifact, NETWORKS, ROOT } from './lib'

const SETTINGS = {
	optimizer: { enabled: true, runs: 200 },
	evmVersion: 'cancun',
	metadata: { bytecodeHash: 'ipfs' },
	remappings: [],
	outputSelection: { '*': { '*': ['evm.bytecode.object', 'abi'] } },
}
const VERIFY = join(ROOT, 'contracts', 'verify')
const src = (f: string) => readFileSync(join(ROOT, 'contracts', 'src', f), 'utf-8')

for (const name of ['RegGateStatus', 'GatedToken']) {
	const input = { language: 'Solidity', sources: { [`src/${name}.sol`]: { content: src(`${name}.sol`) } }, settings: SETTINGS }
	writeFileSync(join(VERIFY, `${name}.standard-input.json`), `${JSON.stringify(input)}\n`)
}

const ctor = (name: 'RegGateStatus' | 'GatedToken', args: readonly unknown[]) => {
	const inputs = loadArtifact(name).abi.find((x: { type: string }) => x.type === 'constructor').inputs
	return encodeAbiParameters(inputs, args as unknown[]).slice(2)
}
// Must match deploy.ts.
const TOKEN_ARGS: Record<string, [string, string, number, boolean]> = {
	gUSD: ['Gated USD (Reg-Gate demo)', 'gUSD', 0, false],
	gAST: ['Gated Asset (Reg-Gate demo)', 'gAST', 2, true],
}

const rows: string[] = []
const blocks: string[] = []
for (const net of Object.values(NETWORKS)) {
	const file = deploymentFile(net)
	if (!existsSync(file)) continue
	const d: Deployment = JSON.parse(readFileSync(file, 'utf-8'))
	const gateArgs = ctor('RegGateStatus', [d.forwarder, BigInt(d.maxAgeSeconds), d.reviewer, d.expectedAuthor, d.simulation])
	rows.push(`| ${net.label} | RegGateStatus | [\`${d.regGateStatus.address}\`](${net.explorer}/address/${d.regGateStatus.address}) | \`RegGateStatus.standard-input.json\` |`)
	blocks.push(`${net.label} RegGateStatus (forwarder, maxAge ${d.maxAgeSeconds}, reviewer, author, simulation ${d.simulation}):\n\n\`\`\`\n${gateArgs}\n\`\`\``)
	for (const t of d.tokens) {
		const [tname, symbol, category, strict] = TOKEN_ARGS[t.symbol]
		const args = ctor('GatedToken', [tname, symbol, d.regGateStatus.address as Address, category, strict, parseEther('1000000')])
		rows.push(`| ${net.label} | GatedToken (${t.symbol}) | [\`${t.address}\`](${net.explorer}/address/${t.address}) | \`GatedToken.standard-input.json\` |`)
		blocks.push(`${net.label} ${t.symbol} ("${tname}", "${symbol}", gate, category ${category}, ${strict ? 'strict' : 'lenient'}, 1,000,000 supply):\n\n\`\`\`\n${args}\n\`\`\``)
	}
}

writeFileSync(
	join(VERIFY, 'README.md'),
	`# Source verification inputs

Generated by \`bun deploy/verify-inputs.ts\` from \`contracts/src\` and \`deploy/deployments/\`.
Solidity standard JSON inputs that rebuild the deployed bytecode byte for byte
(solc v0.8.24+commit.e11b9ed9, optimizer on, 200 runs, EVM version cancun, MIT license).

| Network | Contract | Address | Input |
|---|---|---|---|
${rows.join('\n')}

${blocks.join('\n\n')}
`,
)
console.log(`wrote ${VERIFY}/README.md and standard inputs for ${rows.length} contracts`)
